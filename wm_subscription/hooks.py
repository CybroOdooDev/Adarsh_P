def uninstall_hook(env):
    """Bring back the premium placeholder menus of wm_contracts_billing."""
    for xmlid in ('wm_contracts_billing.menu_wm_subscription_premium',
                  'wm_contracts_billing.menu_wm_subscription_plan_premium'):
        menu = env.ref(xmlid, raise_if_not_found=False)
        if menu:
            menu.active = True
