from datetime import timedelta

from odoo import api, fields, models
from odoo.exceptions import ValidationError
from odoo.tools import format_datetime

LOCATION_SOURCES = [
    ('device', 'Phone GPS'),
    ('manual', 'Entered Manually'),
    ('telematics', 'Estimated (Vehicle Tracker)'),
    ('collection_point', 'Estimated (Collection Point)'),
    ('none', 'Not Available'),
]
ESTIMATED_LOCATION_SOURCES = ('telematics', 'collection_point')


class WmCollectionOrderStatusLog(models.Model):
    """
    Fine-grained, timestamped record of every stop-level moment a driver
    passes through while working a collection order (en route, arrived,
    started, lifted, weighed, completed/flagged).

    This is intentionally a separate child model rather than extra columns
    on wm.collection.order: an order has one current state, but a stop can
    generate more than one event of the same kind (e.g. a driver leaves and
    re-arrives), and this model exists to keep the full sequence, not just
    the latest value of each moment.
    """
    _name = 'wm.collection.order.status.log'
    _description = 'Collection Order Stop Status Log'
    _order = 'timestamp asc, id asc'
    _rec_name = 'status'

    order_id = fields.Many2one(
        'wm.collection.order',
        string='Collection Order',
        required=True,
        ondelete='cascade',
        index=True,
    )
    status = fields.Selection([
        ('en_route', 'En Route'),
        ('arrived', 'Arrived'),
        ('started', 'Started'),
        ('lifted', 'Lifted'),
        ('weighed', 'Weighed'),
        ('completed', 'Completed'),
        ('flagged', 'Flagged'),
    ], required=True)
    timestamp = fields.Datetime(
        required=True,
        default=fields.Datetime.now,
        index=True,
    )
    driver_id = fields.Many2one(
        'res.users',
        default=lambda self: self.env.user,
        help='Driver who reported this status, captured from the authenticated driver app session.',
    )
    latitude = fields.Float(digits=(10, 7))
    longitude = fields.Float(digits=(10, 7))
    location_source = fields.Selection(
        LOCATION_SOURCES,
        help='Where the coordinates come from. Estimated locations were filled in '
             'because the driver\'s phone had no position when the status was logged.',
    )
    note = fields.Char(help='Optional free-text note, e.g. reason for a flagged stop.')
    photo = fields.Binary(attachment=True)
    missed_reason_id = fields.Many2one(
        'wm.missed.reason',
        help="Reason code carried by a 'flagged' event, used to mark the order missed. "
             "Falls back to the generic 'Other' reason when the caller supplies none.",
    )

    # Offline-first clients generate this on-device at the moment of the
    # action, before it may have synced. It lets the driver API safely
    # ignore a retried submission (e.g. after a dropped connection) instead
    # of creating a duplicate row for the same real-world event.
    client_uuid = fields.Char(
        string='Client UUID',
        copy=False,
        help='Unique id generated by the driver app when this event was recorded, used to de-duplicate retried syncs.',
    )

    _client_uuid_uniq = models.Constraint(
        'unique(client_uuid)',
        'This status update has already been recorded (duplicate client UUID).'
    )

    def _format_chatter_time(self, value):
        """
        ``value`` (a naive UTC datetime) as local time for a chatter message,
        with the timezone named, since the message is stored as text and read
        by users of other timezones. The driver's timezone is used, else the
        current user's, else the company's, else UTC.
        """
        self.ensure_one()
        if not value:
            return ''
        tz = (self.driver_id.tz or self.env.user.tz
              or self.order_id.company_id.partner_id.tz or 'UTC')
        return "%s (%s)" % (format_datetime(self.env, value, tz=tz), tz)

    @api.model
    def log_stop_event(
        self, order, status, driver=None, timestamp=None,
        latitude=0.0, longitude=0.0, note='', photo=False, missed_reason=None,
        location_source=False,
    ):
        """Create a stop status log entry for *order*.

        This is the single authoritative creation path used by:
        - the backend ``wm.add.status.log.wizard``
        - the driver-app REST API controller (``wm_driver_app``)

        When neither latitude nor longitude is supplied, the coordinates are
        estimated with the wizard's ``_get_estimated_location`` (vehicle
        telematics, then the collection point) and the log is marked with
        that estimated source, so it is never mistaken for a real position.
        Supplied coordinates keep *location_source* (``manual`` by default).
        """
        if not status:
            raise ValidationError(self.env._("A status is required to log a stop event."))
        if not order or not order.id:
            raise ValidationError(self.env._("A valid collection order is required to log a stop event."))
        if latitude or longitude:
            location_source = location_source or 'manual'
        else:
            latitude, longitude, location_source = (
                self.env['wm.add.status.log.wizard']._get_estimated_location(order))
        return self.create({
            'order_id': order.id,
            'status': status,
            'timestamp': timestamp or fields.Datetime.now(),
            'driver_id': (driver or self.env.user).id,
            'latitude': latitude or 0.0,
            'longitude': longitude or 0.0,
            'location_source': location_source,
            'note': note or '',
            'photo': photo or False,
            'missed_reason_id': missed_reason.id if missed_reason else False,
        })

    @api.model_create_multi
    def create(self, vals_list):
        logs = super().create(vals_list)
        for log in logs:
            if log.order_id:
                # A driver who carries on after flagging reopens the stop, so
                # the order leaves 'missed' before this event is applied and
                # the transitions below see the state the stop was really in.
                if log.status != 'flagged' and log.order_id.state == 'missed':
                    log.order_id.sudo()._resume_from_missed()
                if log.status == 'started' and log.order_id.state == 'dispatched':
                    if log.timestamp:
                        log.order_id.sudo().write({'actual_start': log.timestamp})
                    log.order_id.sudo().action_start()
                elif log.status == 'completed' and log.order_id.state in ('dispatched', 'in_progress'):
                    if log.timestamp:
                        end_ts = log.timestamp
                        start_ts = log.order_id.actual_start
                        if start_ts and end_ts <= start_ts:
                            # Device clock skew / out-of-order sync: clamp
                            # instead of failing the date constraint.
                            end_ts = start_ts + timedelta(seconds=1)
                            log.order_id.message_post(body=self.env._("Completion time %(logged)s reported by the driver app is not after the actual start %(start)s; the actual end was set to %(end)s.", logged=log._format_chatter_time(log.timestamp), start=log._format_chatter_time(start_ts), end=log._format_chatter_time(end_ts)))
                        log.order_id.sudo().write({'actual_end': end_ts})
                    log.order_id.sudo().action_complete()
                elif log.status == 'flagged':
                    log.order_id.sudo()._mark_missed_from_stop(
                        reason=log.missed_reason_id,
                        notes=log.note or '',
                    )
                log.order_id.message_post(
                    body=self.env._("Stop status: %(status)s at %(time)s", status=dict(log._fields['status'].selection).get(log.status), time=log._format_chatter_time(log.timestamp))
                )
        return logs
